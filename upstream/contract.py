"""Keeps contract.yml's generated part in step with the plugin's code.

The plugin's contract with Hermes is mostly in its own code: the Hermes
modules and names it imports, and the routes and sockets it serves under
/api/plugins/conduit_push/. This derives both from the source, so the watch
follows the code without anyone remembering to update it:

    python3 upstream/contract.py check   # CI: fails when contract.yml is stale
    python3 upstream/contract.py write   # rewrites the generated part
    python3 upstream/contract.py changed <hermes checkout> <from ref> <to ref>
                                         # the watched upstream files that changed

The hand-kept parts of contract.yml (watched paths the code can't name,
keywords, known failures) are left as they are.
"""

from __future__ import annotations

import ast
import fnmatch
import json
import re
import sys
from pathlib import Path
from typing import Dict, List, Set, Tuple

ROOT = Path(__file__).resolve().parents[1]
CONTRACT = Path(__file__).resolve().parent / "contract.yml"
BEGIN = "# --- generated by upstream/contract.py: do not edit below ---"

# Hermes' top-level packages and modules: an import of one is part of the contract.
HERMES_TOP = frozenset({
    "agent", "cron", "gateway", "hermes_cli", "hermes_constants", "hermes_state", "hermes_state_ids",
    "hermes_time", "hermes_yaml", "plugins", "tools", "tui_gateway"})
# Not plugin code: tests, dev probes, and the relay and mailbox (Node).
SKIP_DIRS = frozenset({".git", "tests", "probes", "upstream", "relay", "mailbox", "node_modules", "__pycache__"})
ROUTE = re.compile(r'^@router\.(get|post|put|patch|delete|websocket)\("([^"]+)"', re.M)


def plugin_sources() -> List[Path]:
    return sorted(p for p in ROOT.rglob("*.py") if not SKIP_DIRS.intersection(p.relative_to(ROOT).parts))


def _guarded(node: ast.AST, parents: Dict[ast.AST, ast.AST]) -> bool:
    """Whether an import sits in a try whose handlers catch its failure (an optional import)."""
    while node in parents:
        parent = parents[node]
        if isinstance(parent, ast.Try) and node in parent.body:
            return True
        node = parent
    return False


def hermes_imports() -> Dict[str, Dict[str, Set[str]]]:
    """{module: {"required": names, "optional": names}}; a bare ``import m`` records the name ``*``."""
    found: Dict[str, Dict[str, Set[str]]] = {}
    for path in plugin_sources():
        tree = ast.parse(path.read_text(), str(path))
        parents = {child: node for node in ast.walk(tree) for child in ast.iter_child_nodes(node)}
        for node in ast.walk(tree):
            if isinstance(node, ast.ImportFrom) and node.level == 0 and node.module:
                pairs = [(node.module, a.name) for a in node.names]
            elif isinstance(node, ast.Import):
                pairs = [(a.name, "*") for a in node.names]
            else:
                continue
            kind = "optional" if _guarded(node, parents) else "required"
            for module, name in pairs:
                if module.split(".")[0] in HERMES_TOP:
                    found.setdefault(module, {"required": set(), "optional": set()})[kind].add(name)
    for names in found.values():
        names["optional"] -= names["required"]
    return found


def plugin_routes() -> List[str]:
    text = (ROOT / "dashboard" / "plugin_api.py").read_text()
    return sorted({f"{'WS' if m.group(1) == 'websocket' else m.group(1).upper()} {m.group(2)}"
                   for m in ROUTE.finditer(text)}, key=lambda r: (r.split(" ", 1)[1], r))


def module_path(module: str) -> str:
    """The upstream path a module lives at, without its suffix: ``hermes_cli/config`` matches
    ``hermes_cli/config.py`` and ``hermes_cli/config/``."""
    return module.replace(".", "/")


def generated() -> str:
    imports = hermes_imports()
    lines = [BEGIN, "", "# Hermes modules and names the plugin imports. Optional ones are imported inside a try.",
             "imports:"]
    for module in sorted(imports):
        lines.append(f"  {module}:")
        for kind in ("required", "optional"):
            names = sorted(imports[module][kind])
            if names:
                lines.append(f"    {kind}: {json.dumps(names)}")
    lines += ["", "# Where those modules live upstream (a .py file or a package).", "module_paths:"]
    lines += [f"  - {p}" for p in sorted({module_path(m) for m in imports})]
    lines += ["", "# The plugin's routes under /api/plugins/conduit_push/, from dashboard/plugin_api.py.", "routes:"]
    lines += [f"  - {r}" for r in plugin_routes()]
    return "\n".join(lines) + "\n"


def watched(path: str, module_paths: List[str], patterns: List[str]) -> bool:
    """Whether an upstream file is part of the contract: a module the plugin imports, or a watch path."""
    for module in module_paths:
        if path == f"{module}.py" or path.startswith(f"{module}/") and module.count("/") > 0:
            return True
        if path == f"{module}/__init__.py":
            return True
    for pattern in patterns:
        if pattern.endswith("/"):
            if path.startswith(pattern):
                return True
        elif fnmatch.fnmatchcase(path, pattern) and path.count("/") == pattern.count("/"):
            return True
    return False


def changed(repo: str, start: str, end: str) -> List[str]:
    """The watched files that changed between two upstream refs, as ``<status> <path>``."""
    import subprocess
    contract = _load_contract()
    modules = list(contract.get("module_paths") or [])
    patterns = list(contract.get("watch_paths") or [])
    # Names and statuses only: they come from trees, so a blobless clone fetches nothing.
    out = subprocess.run(["git", "-C", repo, "diff", "--no-renames", "--name-status", f"{start}..{end}"],
                         check=True, capture_output=True, text=True).stdout
    lines = []
    for row in out.splitlines():
        status, path = row.split("\t", 1)
        if watched(path, modules, patterns):
            lines.append(f"{status} {path}")
    return lines


def _load_contract() -> dict:
    """contract.yml's data. The format is a small YAML subset (lists and flat maps), read
    without PyYAML so the check runs on a bare Python."""
    try:
        import yaml
        return yaml.safe_load(CONTRACT.read_text()) or {}
    except ImportError:
        pass
    data: dict = {}
    key = None
    for line in CONTRACT.read_text().splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        if not line.startswith(" ") and line.endswith(":"):
            key = line[:-1]
            data[key] = []
        elif key and line.startswith("  - ") and isinstance(data.get(key), list):
            data[key].append(line[4:].strip())
    return data


def split_contract() -> Tuple[str, str]:
    text = CONTRACT.read_text()
    head, sep, tail = text.partition(BEGIN)
    return head, (sep + tail) if sep else ""


def main(argv: List[str]) -> int:
    command = argv[1] if len(argv) > 1 else "check"
    head, current = split_contract()
    fresh = generated()
    if command == "changed":
        print("\n".join(changed(*argv[2:5])))
        return 0
    if command == "write":
        CONTRACT.write_text(head.rstrip("\n") + "\n\n" + fresh)
        return 0
    if command != "check":
        print(__doc__)
        return 2
    if current == fresh:
        print("upstream/contract.yml is current.")
        return 0
    import difflib
    sys.stdout.writelines(difflib.unified_diff(current.splitlines(True), fresh.splitlines(True),
                                               "contract.yml (checked in)", "contract.yml (from the code)"))
    print("\nupstream/contract.yml is stale: the plugin's Hermes imports or routes changed.\n"
          "Run `python3 upstream/contract.py write` and commit the result. If the change adds an\n"
          "integration point, add what it feeds to `notes` in contract.yml.")
    return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv))
